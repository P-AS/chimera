#!/usr/bin/env python3
"""Writes the crash module's table of Vulkan command names, numbered the way the
Vulkan bridge numbers them: miniBox's master list, first name opcode 100. A
blank line or a retired one ("-...") keeps its number and has no name (the same
reading as gen-vk-bridge.py's).

usage: gen-vk-names.py <vk-entry-points.txt> <vk_names.h>
"""
import sys

if len(sys.argv) != 3:
    sys.exit(__doc__)
master = [line.strip() for line in open(sys.argv[1], encoding="ascii").read().split("\n")]
while master and not master[-1]:
    master.pop()
with open(sys.argv[2], "w") as out:
    out.write("/* GENERATED by source/crash/gen-vk-names.py from miniBox's vk-entry-points.txt. */\n")
    out.write("#pragma once\n")
    out.write("#define VK_NAMES_FIRST_OPCODE 100u\n")
    out.write("#define VK_NAMES_COUNT %du\n" % len(master))
    out.write("static const char *const vk_names[%d] = {\n" % max(1, len(master)))
    for name in master:
        out.write('\t"%s",\n' % ("" if name.startswith("-") else name))
    out.write("};\n")
